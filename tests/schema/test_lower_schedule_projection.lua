package.path = "tests/?.lua;./?.lua;./?/init.lua;./lua/?.lua;./lua/?/init.lua;" .. package.path
require("lalin.schema")
local asdl = require("lalin.asdl")
local Code = require("lalin.schema.code")
local Graph = require("lalin.schema.graph")
local Flow = require("lalin.schema.flow")
local Value = require("lalin.schema.value")
local Kernel = require("lalin.schema.kernel")
local Schedule = require("lalin.schema.schedule")
local Lower = require("lalin.schema.lower")
require("lalin.impl.kernel_plan")
require("lalin.impl.schedule_plan")
require("lalin.impl.lower_plan")

local loop = Graph.GraphLoopId("loop:lower")
local kernel_id = Kernel.KernelId("kernel:lower")
local trip = Kernel.KernelTripKnown(Flow.FlowTripCountExact(Code.CodeValueId("trip"), nil, nil))
local body = Kernel.KernelBody(Kernel.KernelDomainFlow(Flow.FlowDomainLoop(loop), trip, Kernel.KernelCounterAbsent), Kernel.KernelLaneProjection({}), Kernel.KernelBindingProjection({}), Kernel.KernelEffectProjection({}), Kernel.KernelResultVoid, Kernel.KernelEquivalenceProof({}))
local plan = Kernel.KernelPlanned(kernel_id, Kernel.KernelSubjectLoop(loop), body)
local schedule = Schedule.SchedulePlanned(Schedule.ScheduleId("schedule:lower"), kernel_id, Schedule.ScheduleScalarIndex, {}, {})
local schedules = Schedule.ScheduleModulePlan(Code.CodeModuleId("m"), Schedule.ScheduleTarget(require("lalin.schema.backend").BackTargetModel(require("lalin.schema.backend").BackTargetNative, {})), { schedule })
local projection = schedules:lower_schedule_projection()
assert(asdl.classof(projection:lookup(kernel_id)) == Lower.LowerScheduleByKernelFound)
assert(asdl.classof(projection:lookup(Kernel.KernelId("missing"))) == Lower.LowerScheduleByKernelMissing)
local kernel_projection = Kernel.KernelModulePlan(Code.CodeModuleId("m"), Flow.FlowFactSet(Code.CodeModuleId("m"), {}, {}, {}, {}, {}, {}, {}), Value.ValueFactSet(Code.CodeModuleId("m"), {}, {}, {}), require("lalin.schema.mem").MemSemanticFactSet(Code.CodeModuleId("m"), {}, {}, {}, {}, {}, {}, {}, {}, {}, {}), require("lalin.schema.effect").EffectFactSet(Code.CodeModuleId("m"), {}, {}, {}), { plan }):lower_kernel_projection()
local candidate = kernel_projection:lookup(loop):lower_fragment_candidate(projection)
assert(asdl.classof(candidate) == Lower.LowerFragmentKernelCandidate)
assert(candidate.kernel == plan and candidate.schedule == schedule)
print("test_lower_schedule_projection: ok")
