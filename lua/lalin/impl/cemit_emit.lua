-- Generate the helper function signature lines
local function helper_header(id, sig)
  local ret = sig.result:c_emit_type()
  local params = {}
  for i = 1, #sig.params do
    params[i] = sig.params[i]:c_emit_type() .. " a" .. tostring(i)
  end
  return { "static inline " .. ret .. " " .. id.text .. "(" .. table.concat(params, ", ") .. ") {" }, ret
end

