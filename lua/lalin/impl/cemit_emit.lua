  local call = self.helper.text .. "(" .. table.concat(args, ", ") .. ")"
  if self.dst then
    out[#out + 1] = indent .. "  " .. self.dst.text .. " = " .. call .. ";"
  else
    out[#out + 1] = indent .. "  " .. call .. ";"
  end
end

