----------------------------------------------------------------------
-- C.CBackendType → c_emit_type / c_emit_decl
----------------------------------------------------------------------

function C.CBackendType:c_emit_type()
  error("missing c_emit_type leaf method for " .. tostring(self), 2)
end
function C.CBackendVoid:c_emit_type() return "void" end
function C.CBackendBool8:c_emit_type() return "bool" end
function C.CBackendScalar:c_emit_type() return self.scalar:c_emit_scalar_name() end
function C.CBackendIndex:c_emit_type() return "size_t" end
function C.CBackendDataPtr:c_emit_type()
  if self.pointee then return self.pointee:c_emit_type() .. "*" end
  return "void*"
end
function C.CBackendQualifiedDataPtr:c_emit_type()
  local base = self.pointee and self.pointee:c_emit_type() or "void"
  local quals = self.qualifiers or ""
  return base .. "* " .. quals
end
function C.CBackendCodePtr:c_emit_type() return "void(*)(void)" end
function C.CBackendImportedCodePtr:c_emit_type()
  return self.sig and self.sig:c_emit_type() or "void(*)(void)"
end
function C.CBackendNamed:c_emit_type() return self.id.spelling end
function C.CBackendArray:c_emit_type()
  return self.elem:c_emit_type() .. "[" .. tostring(self.count) .. "]"
end
function C.CBackendSliceDescriptor:c_emit_type() return "lalin_slice_t" end
function C.CBackendByteSpanDescriptor:c_emit_type() return "lalin_bytespan_t" end
function C.CBackendViewDescriptor:c_emit_type() return "lalin_view_t" end
function C.CBackendClosureDescriptor:c_emit_type() return "lalin_closure_t" end
function C.CBackendAbiHiddenOutPtr:c_emit_type()
  if self.pointee then return self.pointee:c_emit_type() .. "*" end
  return "void*"
end
function C.CBackendVector:c_emit_type()
  local elem = self.elem:c_emit_type()
  return elem .. " __attribute__((vector_size(" .. tostring(self.lanes * 4) .. ")))"
end

function C.CBackendType:c_emit_decl(name)
  return self:c_emit_type() .. " " .. (name or "")
end

----------------------------------------------------------------------
-- C.CBackendStmt → c_emit_stmt
----------------------------------------------------------------------

function C.CBackendStmt:c_emit_stmt()
  return "/* " .. tostring(self) .. " */;"
end

----------------------------------------------------------------------
-- C.CBackendAtom / C.CBackendPlace → c_emit_atom / c_emit_place
----------------------------------------------------------------------

function C.CBackendAtom:c_emit_atom() return tostring(self) end
function C.CBackendPlace:c_emit_place() return tostring(self) end

----------------------------------------------------------------------
-- CodeSig / CFuncSig → c_emit_signature
----------------------------------------------------------------------

function C.CFuncSig:c_emit_signature()
  local ret = self.result and self.result:c_emit_type() or "void"
  local params = {}
  for _, p in ipairs(self.params or {}) do
    params[#params + 1] = p:c_emit_type()
  end
  return ret .. " " .. (self.name or "fn") .. "(" .. table.concat(params, ", ") .. ")"
end
