-- impl/cemit_emit.lua
-- Methods on Cemit.*, Core.*, and C.* types for final C text emission.
-- Ported from emit_c_lower.lua.

require("lalin.schema_v2")

local Cemit = require("lalin.schema_v2.cemit")
local C     = require("lalin.schema_v2.c")
local Core  = require("lalin.schema_v2.core")
local Code  = require("lalin.schema_v2.code")

----------------------------------------------------------------------
-- CEmitMachine → emit_module / emit_source / emit_header / emit_combined
----------------------------------------------------------------------

function Cemit.CEmitMachine:emit_module(code_module, lower_module)
  local source = self:emit_source(code_module, lower_module)
  local header = self:emit_header(code_module)
  return Cemit.CEmitArtifact(source, header, "", source .. "\n" .. header)
end

function Cemit.CEmitMachine:emit_source(code_module, lower_module)
  local lines = {}

  -- Emit includes
  lines[#lines + 1] = '#include <stdint.h>'
  lines[#lines + 1] = '#include <stddef.h>'
  lines[#lines + 1] = '#include <stdbool.h>'
  lines[#lines + 1] = ''

  -- Emit each function from the C backend unit
  if lower_module and lower_module.c_unit then
    local c_unit = lower_module.c_unit
    for _, func in ipairs(c_unit.funcs or {}) do
      -- function signature
      if func.sig then
        lines[#lines + 1] = func.sig:c_emit_signature() .. ' {'
      else
        lines[#lines + 1] = '/* function ' .. (func.name or 'unknown') .. ' */'
        lines[#lines + 1] = '{'
      end
      -- function body blocks
      for _, block in ipairs(func.blocks or {}) do
        for _, stmt in ipairs(block.stmts or {}) do
          lines[#lines + 1] = '  ' .. stmt:c_emit_stmt()
        end
      end
      lines[#lines + 1] = '}'
      lines[#lines + 1] = ''
    end
  end

  return table.concat(lines, '\n')
end

function Cemit.CEmitMachine:emit_header(code_module)
  local lines = {}
  lines[#lines + 1] = '/* Auto-generated by Lalin C emitter */'
  lines[#lines + 1] = '#ifndef LALIN_EMIT_H'
  lines[#lines + 1] = '#define LALIN_EMIT_H'
  lines[#lines + 1] = ''
  lines[#lines + 1] = '#include <stdint.h>'
  lines[#lines + 1] = '#include <stddef.h>'
  lines[#lines + 1] = '#include <stdbool.h>'
  lines[#lines + 1] = ''
  -- emit function declarations
  if code_module then
    for _, func in ipairs(code_module.funcs or {}) do
      if func.sig then
        lines[#lines + 1] = func.sig:c_emit_signature() .. ';'
      end
    end
  end
  lines[#lines + 1] = ''
  lines[#lines + 1] = '#endif /* LALIN_EMIT_H */'
  return table.concat(lines, '\n')
end

function Cemit.CEmitMachine:emit_combined(code_module, lower_module)
  local header = self:emit_header(code_module)
  local source = self:emit_source(code_module, lower_module)
  return header .. '\n' .. source
end

