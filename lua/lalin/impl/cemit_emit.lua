-- C.CBackendFuncSig → c_emit_signature
----------------------------------------------------------------------

function C.CBackendFuncSig:c_emit_signature(name)
  local ret = self.result:c_emit_type()
  local params = {}
  for _, p in ipairs(self.params or {}) do
    params[#params + 1] = p:c_emit_type()
  end
  if #params == 0 then params[1] = "void" end
  return ret .. " " .. (name or "fn") .. "(" .. table.concat(params, ", ") .. ")"
end

