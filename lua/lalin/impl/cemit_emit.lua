function C.CBackendUnit:c_emit_sig_projection()
  local entries = {}
  for i = 1, #self.sigs do entries[i] = C.CBackendFuncSigEntry(self.sigs[i].id, self.sigs[i]) end
  return C.CBackendFuncSigProjection(entries)
end
function C.CBackendFuncSigProjection:c_emit_sig_lookup(id)
  for i = 1, #self.entries do if self.entries[i].id == id then return C.CBackendFuncSigFound(self.entries[i]) end end
  return C.CBackendFuncSigMissing(id)
end

local function func_params(params)
  local out = {}
  if not params or #params == 0 then return "void" end
  for i, p in ipairs(params) do
    out[i] = p.ty:c_emit_decl(p.id.text)
  end
  return table.concat(out, ", ")
end

-- Sanitize a string for use as a C identifier
local function sanitize(s)
  s = tostring(s or "x"):gsub("[^%w_]", "_")
  if s:match("^%d") then s = "_" .. s end
  if s == "" then s = "x" end
  return s
end

----------------------------------------------------------------------
-- CEmitMachine → emit_module / emit_source / emit_header
----------------------------------------------------------------------

function Cemit.CEmitMachine:emit_module(c_unit)
  local source = self:emit_source(c_unit)
  local header = self:emit_header(c_unit)
  return { source = source, header = header }
end

function Cemit.CEmitMachine:emit_source(c_unit)
  local lines = {}
  lines[#lines + 1] = '/* generated by lalin C backend */'

  -- Includes
  lines[#lines + 1] = '#include <stdint.h>'
  lines[#lines + 1] = '#include <stddef.h>'
  lines[#lines + 1] = '#include <stdbool.h>'
  lines[#lines + 1] = '#include <string.h>'
  lines[#lines + 1] = '#include <stdlib.h>'
  lines[#lines + 1] = ''

  -- Type declarations
  if c_unit.types and #c_unit.types > 0 then
    lines[#lines + 1] = ''
    lines[#lines + 1] = '/* type declarations */'
    for _, td in ipairs(c_unit.types) do
      td:c_emit_type_decl(lines)
    end
  end

  -- Helpers
  if c_unit.helpers and #c_unit.helpers > 0 then
    for _, h in ipairs(c_unit.helpers) do
      for _, hl in ipairs(h:c_emit_helper_lines()) do
        lines[#lines + 1] = hl
      end
      lines[#lines + 1] = ''
    end
  end

  -- Function bodies
  local signatures = c_unit:c_emit_sig_projection()
  if c_unit.funcs then
    for _, func in ipairs(c_unit.funcs) do
      func:c_emit_func_source(signatures, lines)
      lines[#lines + 1] = ''
    end
  end

  return table.concat(lines, '\n')
end

function Cemit.CEmitMachine:emit_header(c_unit)
  local module_name = c_unit.module_name or "lalin"
  local guard = sanitize(module_name .. "_h"):upper()
  local lines = {}
  lines[#lines + 1] = '/* generated by lalin C backend */'
  lines[#lines + 1] = '#ifndef ' .. guard
  lines[#lines + 1] = '#define ' .. guard
  lines[#lines + 1] = ''
  lines[#lines + 1] = '#include <stdint.h>'
  lines[#lines + 1] = '#include <stddef.h>'
  lines[#lines + 1] = '#include <stdbool.h>'
  lines[#lines + 1] = ''

  -- Type declarations
  if c_unit.types and #c_unit.types > 0 then
    lines[#lines + 1] = '/* type declarations */'
    for _, td in ipairs(c_unit.types) do
      td:c_emit_type_decl(lines)
    end
    lines[#lines + 1] = ''
  end

  -- Function prototypes

  local signatures = c_unit:c_emit_sig_projection()
  if c_unit.funcs then
    for _, func in ipairs(c_unit.funcs) do
      signatures:c_emit_sig_lookup(func.sig):c_emit_prototype(func, lines)
    end
  end
  lines[#lines + 1] = ''
  lines[#lines + 1] = '#endif /* ' .. guard .. ' */'
  return table.concat(lines, '\n')
end

