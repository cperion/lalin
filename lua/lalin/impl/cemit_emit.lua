function C.CBackendAggregateInit:c_emit_stmt(out, indent)
  for _, f in ipairs(self.fields or {}) do
    local place_str = self.place:c_emit_place()
    out[#out + 1] = indent .. "  " .. place_str .. "." .. f.field.text .. " = " .. f.value:c_emit_atom() .. ";"
