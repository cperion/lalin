  for _, a in ipairs(self.args or {}) do
    args[#args + 1] = a:c_emit_atom()
  end
  local call = callee .. "(" .. table.concat(args, ", ") .. ")"
  if self.dst then
    out[#out + 1] = indent .. "  " .. self.dst.text .. " = " .. call .. ";"
  else
    out[#out + 1] = indent .. "  " .. call .. ";"
  end
end

function C.CBackendComment:c_emit_stmt(out, indent)
