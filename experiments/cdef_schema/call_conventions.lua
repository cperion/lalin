local ffi = require("ffi")
local bit = require("bit")
local util = require("jit.util")
local vmdef = require("jit.vmdef")

ffi.cdef[[
typedef struct {
    uint64_t enters;
    uint64_t unwinds;
    uint32_t remaining;
    uint16_t sp;
    uint8_t suspended;
    uint8_t suspend_each;
    uint16_t frames[96];
} CallConventionsV1_State;
 ]]

local MAX_DEPTH = 90

local function compile(lines, label)
    local source = table.concat(lines, "\n")
    local loader, message = loadstring(source, "@call-conventions-" .. label)
    if not loader then error(message .. " (generated bytes=" .. #source .. ")") end
    return loader()(ffi), source
end

local function local_declaration(prefix, depth)
    local names = {}
    for index = 1, depth do names[index] = prefix .. index end
    return "  local " .. table.concat(names, ", ")
end

local function build_tail(depth)
    local lines = {
        "return function(ffi)",
        "  local state = ffi.new('CallConventionsV1_State')",
        local_declaration("block_", depth),
    }
    for index = 1, depth - 1 do
        lines[#lines + 1] = ("  block_%d = function(self)"):format(index)
        lines[#lines + 1] = "    self.enters = self.enters + 1"
        lines[#lines + 1] = ("    return block_%d(self)"):format(index + 1)
        lines[#lines + 1] = "  end"
    end
    lines[#lines + 1] = ("  block_%d = function(self)"):format(depth)
    lines[#lines + 1] = "    self.enters = self.enters + 1"
    lines[#lines + 1] = "    local remaining = self.remaining"
    lines[#lines + 1] = "    if remaining <= 1 then return self.enters end"
    lines[#lines + 1] = "    self.remaining = remaining - 1"
    lines[#lines + 1] = "    return block_1(self)"
    lines[#lines + 1] = "  end"
    lines[#lines + 1] = "  local function run(cycles)"
    lines[#lines + 1] = "    state.enters, state.unwinds = 0, 0"
    lines[#lines + 1] = "    state.remaining, state.sp = cycles, 0"
    lines[#lines + 1] = "    return block_1(state)"
    lines[#lines + 1] = "  end"
    lines[#lines + 1] = "  return { run = run, state = state, first = block_1 }"
    lines[#lines + 1] = "end"
    return compile(lines, "tail-" .. depth)
end

local function build_host(depth)
    local lines = {
        "return function(ffi)",
        "  local state = ffi.new('CallConventionsV1_State')",
        local_declaration("call_", depth),
    }
    for index = 1, depth - 1 do
        lines[#lines + 1] = ("  call_%d = function(self)"):format(index)
        lines[#lines + 1] = "    self.enters = self.enters + 1"
        lines[#lines + 1] = ("    local result = call_%d(self)"):format(index + 1)
        lines[#lines + 1] = "    self.unwinds = self.unwinds + 1"
        lines[#lines + 1] = "    return result"
        lines[#lines + 1] = "  end"
    end
    lines[#lines + 1] = ("  call_%d = function(self)"):format(depth)
    lines[#lines + 1] = "    self.enters = self.enters + 1"
    lines[#lines + 1] = "    return 1"
    lines[#lines + 1] = "  end"
    lines[#lines + 1] = "  local function run(cycles)"
    lines[#lines + 1] = "    state.enters, state.unwinds = 0, 0"
    lines[#lines + 1] = "    local result = 0"
    lines[#lines + 1] = "    for _ = 1, cycles do result = result + call_1(state) end"
    lines[#lines + 1] = "    return state.enters, state.unwinds, result"
    lines[#lines + 1] = "  end"
    lines[#lines + 1] = "  return { run = run, state = state, first = call_1 }"
    lines[#lines + 1] = "end"
    return compile(lines, "host-" .. depth)
end

local function build_explicit(depth)
    local lines = {
        "return function(ffi)",
        "  local state = ffi.new('CallConventionsV1_State')",
        local_declaration("enter_", depth),
        local_declaration("resume_", depth),
    }
    for index = 1, depth do
        lines[#lines + 1] = ("  enter_%d = function(self)"):format(index)
        lines[#lines + 1] = "    local sp = self.sp"
        lines[#lines + 1] = ("    self.frames[sp] = %d"):format(index)
        lines[#lines + 1] = "    self.sp = sp + 1"
        lines[#lines + 1] = "    self.enters = self.enters + 1"
        if index < depth then
            lines[#lines + 1] = ("    return enter_%d(self)"):format(index + 1)
        else
            lines[#lines + 1] = "    if self.suspend_each ~= 0 then"
            lines[#lines + 1] = "      self.suspended = 1"
            lines[#lines + 1] = "      return self.sp"
            lines[#lines + 1] = "    end"
            lines[#lines + 1] = ("    return resume_%d(self)"):format(depth)
        end
        lines[#lines + 1] = "  end"
    end
    for index = depth, 1, -1 do
        lines[#lines + 1] = ("  resume_%d = function(self)"):format(index)
        lines[#lines + 1] = "    local sp = self.sp - 1"
        lines[#lines + 1] = ("    if self.frames[sp] ~= %d then error('corrupt explicit frame') end"):format(index)
        lines[#lines + 1] = "    self.sp = sp"
        lines[#lines + 1] = "    self.unwinds = self.unwinds + 1"
        if index > 1 then
            lines[#lines + 1] = ("    return resume_%d(self)"):format(index - 1)
        else
            lines[#lines + 1] = "    local remaining = self.remaining"
            lines[#lines + 1] = "    if remaining <= 1 then"
            lines[#lines + 1] = "      self.remaining, self.suspended = 0, 0"
            lines[#lines + 1] = "      return self.enters"
            lines[#lines + 1] = "    end"
            lines[#lines + 1] = "    self.remaining = remaining - 1"
            lines[#lines + 1] = "    return enter_1(self)"
        end
        lines[#lines + 1] = "  end"
    end
    lines[#lines + 1] = "  local function reset(cycles, suspend_each)"
    lines[#lines + 1] = "    state.enters, state.unwinds = 0, 0"
    lines[#lines + 1] = "    state.remaining, state.sp = cycles, 0"
    lines[#lines + 1] = "    state.suspended, state.suspend_each = 0, suspend_each"
    lines[#lines + 1] = "  end"
    lines[#lines + 1] = "  local function run(cycles) reset(cycles, 0); return enter_1(state) end"
    lines[#lines + 1] = "  local function start_suspended(cycles) reset(cycles, 1); return enter_1(state) end"
    lines[#lines + 1] = "  local function resume()"
    lines[#lines + 1] = "    if state.suspended == 0 then error('machine is not suspended') end"
    lines[#lines + 1] = "    state.suspended = 0"
    lines[#lines + 1] = ("    return resume_%d(state)"):format(depth)
    lines[#lines + 1] = "  end"
    lines[#lines + 1] = "  return { run = run, start_suspended = start_suspended, resume = resume,"
    lines[#lines + 1] = "    state = state, first = enter_1, first_resume = resume_1 }"
    lines[#lines + 1] = "end"
    return compile(lines, "explicit-" .. depth)
end

local function bytecodes(fn)
    local names = {}
    for pc = 0, 1000 do
        local instruction = util.funcbc(fn, pc)
        if instruction == nil then break end
        local opcode = bit.band(instruction, 0xff)
        names[#names + 1] = vmdef.bcnames:sub(opcode * 6 + 1, opcode * 6 + 6):match("%S+")
    end
    return names
end

local function has_bytecode(fn, wanted)
    for _, name in ipairs(bytecodes(fn)) do
        if name == wanted then return true end
    end
    return false
end

local M = { MAX_DEPTH = MAX_DEPTH }

function M.build(depth)
    assert(type(depth) == "number" and depth >= 1 and depth <= MAX_DEPTH
        and depth == math.floor(depth), "depth must be an integer from 1 through " .. MAX_DEPTH)
    local tail, tail_source = build_tail(depth)
    local host, host_source = build_host(depth)
    local explicit, explicit_source = build_explicit(depth)
    return {
        depth = depth,
        tail = tail,
        host = host,
        explicit = explicit,
        sources = { tail = tail_source, host = host_source, explicit = explicit_source },
    }
end

M.bytecodes = bytecodes
M.has_bytecode = has_bytecode

return M

