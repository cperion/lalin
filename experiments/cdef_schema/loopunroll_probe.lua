package.path = "./lua/?.lua;./lua/?/init.lua;./?.lua;./?/init.lua;" .. package.path

local ffi = require("ffi")
local jit = require("jit")
local util = require("jit.util")
local vmdef = require("jit.vmdef")

local depth = tonumber(arg[1]) or 8
local loopunroll = tonumber(arg[2]) or 15
local cycles = tonumber(arg[3]) or 100000
local cap_mode = arg[4] or "default"

assert(depth >= 1 and depth == math.floor(depth), "depth must be a positive integer")
assert(loopunroll >= 0 and loopunroll <= 2147483647,
    "loopunroll must fit LuaJIT's non-negative int32 parameter")
assert(cycles >= 1 and cycles == math.floor(cycles), "cycles must be a positive integer")
assert(cap_mode == "default" or cap_mode == "wide" or cap_mode == "max",
    "cap mode must be default, wide, or max")

ffi.cdef[[
typedef struct {
    uint64_t transitions;
    uint32_t remaining;
} LoopUnrollProbeV1_State;
 ]]

local function build_chain(count)
    local lines = { "local state = ffi.new('LoopUnrollProbeV1_State')" }

    for index = 1, count - 1 do
        lines[#lines + 1] = ("block_%d = function(self)"):format(index)
        lines[#lines + 1] = "  self.transitions = self.transitions + 1"
        lines[#lines + 1] = ("  return block_%d(self)"):format(index + 1)
        lines[#lines + 1] = "end"
    end

    lines[#lines + 1] = ("block_%d = function(self)"):format(count)
    lines[#lines + 1] = "  self.transitions = self.transitions + 1"
    lines[#lines + 1] = "  local remaining = self.remaining"
    lines[#lines + 1] = "  if remaining == 0 then return self.transitions end"
    lines[#lines + 1] = "  self.remaining = remaining - 1"
    lines[#lines + 1] = "  return block_1(self)"
    lines[#lines + 1] = "end"

    lines[#lines + 1] = "return function(cycles)"
    lines[#lines + 1] = "  state.transitions = 0"
    lines[#lines + 1] = "  state.remaining = cycles - 1"
    lines[#lines + 1] = "  return block_1(state)"
    lines[#lines + 1] = "end"

    local source = table.concat(lines, "\n")
    local loader, message = loadstring(source, "@loopunroll-probe-depth-" .. count)
    if not loader then error(message .. " (generated bytes=" .. #source .. ")") end
    local environment = { ffi = ffi }
    setfenv(loader, environment)
    return loader(), #source
end

local options = {
    "hotloop=10",
    "hotexit=2",
    "loopunroll=" .. loopunroll,
}
if cap_mode == "wide" then
    options[#options + 1] = "maxrecord=30000"
    options[#options + 1] = "maxirconst=10000"
    options[#options + 1] = "maxsnap=10000"
elseif cap_mode == "max" then
    -- IR operands and stored trace/snapshot counts are 16-bit. Raise only
    -- capacity ceilings near those hard representations. Instability, recursion,
    -- side-trace, and retry limits remain safety policies rather than capacities.
    options[#options + 1] = "maxrecord=32700"
    options[#options + 1] = "maxirconst=32000"
    options[#options + 1] = "maxsnap=65000"
end
jit.opt.start(unpack(options))

local run, source_bytes = build_chain(depth)
local trace = { starts = 0, stops = 0, aborts = 0, reasons = {} }

local function on_trace(what, _trace_number, _func, _pc, error_code)
    if what == "start" then trace.starts = trace.starts + 1
    elseif what == "stop" then trace.stops = trace.stops + 1
    elseif what == "abort" then
        trace.aborts = trace.aborts + 1
        local reason = vmdef.traceerr[error_code] or tostring(error_code)
        trace.reasons[reason] = (trace.reasons[reason] or 0) + 1
    end
end

jit.flush()
jit.attach(on_trace, "trace")

local warm_calls = cap_mode == "max" and 4 or 20
local warm_cycles = cap_mode == "max" and 20 or 200
for _ = 1, warm_calls do
    local result = run(warm_cycles)
    assert(tonumber(result) == depth * warm_cycles)
end

jit.attach(on_trace)

local trace_count, root_loops, instruction_count = 0, 0, 0
for trace_number = 1, 10000 do
    local info = util.traceinfo(trace_number)
    if info == nil then break end
    trace_count = trace_count + 1
    instruction_count = instruction_count + (info.nins or 0)
    if info.linktype == "loop" or info.linktype == "tail-recursion"
        or info.linktype == "up-recursion" or info.linktype == "down-recursion"
        or info.link == trace_number then
        root_loops = root_loops + 1
    end
end

local execution_mode = "jit"
if root_loops == 0 then
    -- Prevent a failed maximum-limit configuration from retrying compilation
    -- throughout the timed run and turning a diagnostic probe into a long hang.
    jit.off()
    execution_mode = "interpreter"
    cycles = math.min(cycles, math.max(1, math.floor(100000 / depth)))
end

collectgarbage()
collectgarbage()
collectgarbage("stop")
local heap_before = collectgarbage("count")
local start = os.clock()
local result = run(cycles)
local elapsed = os.clock() - start
local heap_growth = collectgarbage("count") - heap_before
collectgarbage("restart")

local expected = depth * cycles
assert(tonumber(result) == expected,
    ("bad transition count: expected %d got %s"):format(expected, tostring(result)))

local reasons = {}
for reason, count in pairs(trace.reasons) do
    reasons[#reasons + 1] = reason .. ":" .. count
end
table.sort(reasons)

print(("depth=%d loopunroll=%d caps=%s execution=%s source=%d traces=%d loops=%d nins=%d starts=%d stops=%d aborts=%d"):format(
    depth, loopunroll, cap_mode, execution_mode, source_bytes, trace_count, root_loops,
    instruction_count, trace.starts, trace.stops, trace.aborts))
print(("cycles=%d transitions=%d elapsed_ms=%.3f ns_per_transition=%.3f heap_kb=%.3f"):format(
    cycles, expected, elapsed * 1000, elapsed * 1e9 / expected, heap_growth))
print("abort_reasons=" .. (#reasons == 0 and "none" or table.concat(reasons, ",")))

